/** 오늘 기준 n일 뒤 날짜를 YYYY-MM-DD 로 반환 */
export function isoDate(offsetDays = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10);
}

