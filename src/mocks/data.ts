const SLOT_TIMES: [string, string][] = [
  ['10:00', '12:00'],
  ['13:00', '15:00'],
  ['15:30', '17:30'],
];

/** 향후 14일치 예약 슬롯을 결정적으로 생성 (같은 날 = 같은 결과) */
export const TIME_SLOTS: TimeSlot[] = SPACES.flatMap((space) =>
  Array.from({ length: 14 }).flatMap((_, dayOffset) =>
    SLOT_TIMES.map(([start, end], slotIndex) => {
      const seed = (space.id.length + dayOffset * 3 + slotIndex * 5) % 7;
      const remaining = Math.max(0, Math.min(space.capacity, seed * 2 - 1));
      return {
        id: `${space.id}-${isoDate(dayOffset)}-${slotIndex}`,
        spaceId: space.id,
        date: isoDate(dayOffset),
        start,
        end,
        remaining,
        capacity: space.capacity,
      };
    })
  )
);

